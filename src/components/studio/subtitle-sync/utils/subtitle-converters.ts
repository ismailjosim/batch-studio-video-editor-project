import type { SubtitleCue } from "../subtitle-sync-types";
import { formatTimecode } from "./time-utils";

/**
 * Formats milliseconds into WebVTT timecode (00:00:00.000)
 */
export function formatVttTimecode(ms: number): string {
  const safe = Math.max(0, ms);
  const hours = Math.floor(safe / 3600000);
  const minutes = Math.floor((safe % 3600000) / 60000);
  const seconds = Math.floor((safe % 60000) / 1000);
  const millis = safe % 1000;

  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}.${String(millis).padStart(3, "0")}`;
}

/**
 * Formats milliseconds into ASS timecode (H:MM:SS.CC)
 */
export function formatAssTimecode(ms: number): string {
  const safe = Math.max(0, ms);
  const hours = Math.floor(safe / 3600000);
  const minutes = Math.floor((safe % 3600000) / 60000);
  const seconds = Math.floor((safe % 60000) / 1000);
  const centis = Math.floor((safe % 1000) / 10);

  return `${hours}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}.${String(centis).padStart(2, "0")}`;
}

/**
 * Serializes cues into standard SubRip (.srt) format.
 */
export function renderSrt(cues: SubtitleCue[]): string {
  const sorted = [...cues].sort((a, b) => a.startMs - b.startMs);
  const blocks = sorted.map((cue, index) => {
    const startMs = Math.max(0, cue.startMs);
    const endMs = Math.max(startMs + 50, cue.endMs);
    return `${index + 1}\n${formatTimecode(startMs)} --> ${formatTimecode(endMs)}\n${cue.text.trim()}`;
  });
  return blocks.join("\n\n") + (blocks.length ? "\n" : "");
}

/**
 * Serializes cues into WebVTT (.vtt) format for web players.
 */
export function renderVtt(cues: SubtitleCue[]): string {
  const sorted = [...cues].sort((a, b) => a.startMs - b.startMs);
  const header = "WEBVTT - Exported by Batch Studio Suite\n\n";
  const blocks = sorted.map((cue, index) => {
    const startMs = Math.max(0, cue.startMs);
    const endMs = Math.max(startMs + 50, cue.endMs);
    return `${index + 1}\n${formatVttTimecode(startMs)} --> ${formatVttTimecode(endMs)}\n${cue.text.trim()}`;
  });
  return header + blocks.join("\n\n") + (blocks.length ? "\n" : "");
}

/**
 * Serializes cues into Advanced SubStation Alpha (.ass) format.
 */
export function renderAss(
  cues: SubtitleCue[],
  title = "Batch Studio Suite",
): string {
  const sorted = [...cues].sort((a, b) => a.startMs - b.startMs);
  const header = `[Script Info]
; Script generated by Batch Studio Suite
Title: ${title}
ScriptType: v4.00+
WrapStyle: 0
PlayResX: 1920
PlayResY: 1080
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Plus Jakarta Sans,72,&H00FFFFFF,&H0000D2FF,&H00000000,&H80000000,-1,0,0,0,100,100,0,0,1,4,2,2,40,40,60,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

  const lines = sorted.map((cue) => {
    const start = formatAssTimecode(cue.startMs);
    const end = formatAssTimecode(cue.endMs);
    const sanitizedText = cue.text.replace(/\r?\n/g, "\\N");
    return `Dialogue: 0,${start},${end},Default,,0,0,0,,${sanitizedText}`;
  });

  return header + lines.join("\n") + (lines.length ? "\n" : "");
}

/**
 * Serializes cues into clean plain text transcript (.txt).
 */
export function renderTxt(
  cues: SubtitleCue[],
  includeTimestamps = false,
): string {
  const sorted = [...cues].sort((a, b) => a.startMs - b.startMs);
  if (!includeTimestamps) {
    return sorted
      .map((c) => c.text.trim())
      .filter(Boolean)
      .join("\n\n");
  }

  return sorted
    .map((c) => `[${formatTimecode(c.startMs)}] ${c.text.trim()}`)
    .join("\n");
}

/**
 * Serializes cues into structured JSON (.json) for data pipelines.
 */
export function renderJson(cues: SubtitleCue[]): string {
  const sorted = [...cues].sort((a, b) => a.startMs - b.startMs);
  const data = sorted.map((cue, idx) => ({
    id: idx + 1,
    startMs: cue.startMs,
    endMs: cue.endMs,
    startTime: formatTimecode(cue.startMs),
    endTime: formatTimecode(cue.endMs),
    durationMs: cue.endMs - cue.startMs,
    text: cue.text.trim(),
  }));

  return JSON.stringify(data, null, 2);
}
